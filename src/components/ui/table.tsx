import * as React from "react";

import { cn } from "@/components/lib/utils";

/**
 * A data table.
 *
 * Presentational only: no sorting, no selection, no state. Every Runtime list
 * is a projection of rows a server query already ordered and scoped, so a
 * client-side sort would reorder something the server deliberately ordered —
 * newest first for a history, plan order for a run's steps — and a selection
 * model would be a state machine for a table that selects nothing.
 *
 * The wrapper scrolls horizontally rather than truncating. A run's step list
 * carries a target account, a state, and two timestamps, and on a phone the
 * honest answer to "it does not fit" is to let it scroll rather than to hide
 * columns a user came to read.
 */
const Table = React.forwardRef<
  HTMLTableElement,
  React.HTMLAttributes<HTMLTableElement>
>(({ className, ...props }, ref) => (
  <div className="relative w-full overflow-x-auto">
    <table
      ref={ref}
      className={cn("w-full caption-bottom text-sm", className)}
      {...props}
    />
  </div>
));
Table.displayName = "Table";

